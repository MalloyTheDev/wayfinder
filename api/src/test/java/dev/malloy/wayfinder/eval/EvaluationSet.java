package dev.malloy.wayfinder.eval;

import dev.malloy.wayfinder.domain.PriceBand;
import dev.malloy.wayfinder.domain.Region;
import dev.malloy.wayfinder.domain.TravelerPreferences;
import dev.malloy.wayfinder.domain.VacationType;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.EnumSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * The hand-labelled evaluation set: personas and the relevance judgments for each.
 *
 * Loaded from CSV rather than written in Java so the labels can be reviewed as data in a
 * pull request without reading code around them. The judgments file carries the warning
 * that matters: these are editorial judgments, deliberately not derived from the scoring
 * formula, because ground truth generated by the thing under test measures nothing.
 */
record EvaluationSet(List<Persona> personas, Map<String, Map<String, Integer>> judgments) {

    record Persona(String name, TravelerPreferences preferences) {
    }

    static EvaluationSet load() {
        return new EvaluationSet(readPersonas(), readJudgments());
    }

    /** Judgments for one persona, keyed by destination slug. */
    Map<String, Integer> judgmentsFor(String persona) {
        Map<String, Integer> forPersona = judgments.get(persona);
        if (forPersona == null || forPersona.isEmpty()) {
            throw new IllegalStateException("no judgments recorded for persona: " + persona);
        }
        return forPersona;
    }

    private static List<Persona> readPersonas() {
        List<Persona> personas = new ArrayList<>();
        for (String[] row : readCsv("eval/personas.csv", 4)) {
            personas.add(new Persona(row[0], new TravelerPreferences(
                parseEnums(row[1], VacationType.class),
                parseEnums(row[2], Region.class),
                PriceBand.valueOf(row[3]))));
        }
        if (personas.isEmpty()) {
            throw new IllegalStateException("personas.csv defined no personas");
        }
        return List.copyOf(personas);
    }

    private static Map<String, Map<String, Integer>> readJudgments() {
        Map<String, Map<String, Integer>> byPersona = new LinkedHashMap<>();
        for (String[] row : readCsv("eval/judgments.csv", 3)) {
            int relevance = Integer.parseInt(row[2]);
            if (relevance < 0 || relevance > 3) {
                throw new IllegalStateException(
                    "relevance must be 0 to 3, got " + relevance + " for " + row[0] + "/" + row[1]);
            }
            Map<String, Integer> forPersona =
                byPersona.computeIfAbsent(row[0], key -> new LinkedHashMap<>());
            if (forPersona.put(row[1], relevance) != null) {
                throw new IllegalStateException(
                    "duplicate judgment for " + row[0] + "/" + row[1]);
            }
        }
        return Map.copyOf(byPersona);
    }

    private static <E extends Enum<E>> Set<E> parseEnums(String value, Class<E> type) {
        if (value == null || value.isBlank()) {
            return EnumSet.noneOf(type);
        }
        return Arrays.stream(value.split("\\|"))
            .map(String::strip)
            .filter(part -> !part.isEmpty())
            .map(part -> Enum.valueOf(type, part))
            .collect(java.util.stream.Collectors.toCollection(() -> EnumSet.noneOf(type)));
    }

    /** Minimal CSV: comments start with #, blank lines ignored, no quoting needed. */
    private static List<String[]> readCsv(String resource, int expectedColumns) {
        List<String[]> rows = new ArrayList<>();
        try (InputStream in = EvaluationSet.class.getClassLoader().getResourceAsStream(resource)) {
            if (in == null) {
                throw new IllegalStateException("missing evaluation resource: " + resource);
            }
            try (BufferedReader reader =
                     new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
                String line;
                int lineNumber = 0;
                while ((line = reader.readLine()) != null) {
                    lineNumber++;
                    String trimmed = line.strip();
                    if (trimmed.isEmpty() || trimmed.startsWith("#")) {
                        continue;
                    }
                    String[] parts = trimmed.split(",", -1);
                    if (parts.length != expectedColumns) {
                        throw new IllegalStateException(resource + ":" + lineNumber
                            + " expected " + expectedColumns + " columns, got " + parts.length);
                    }
                    for (int i = 0; i < parts.length; i++) {
                        parts[i] = parts[i].strip();
                    }
                    rows.add(parts);
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException("could not read " + resource, e);
        }
        return rows;
    }
}
